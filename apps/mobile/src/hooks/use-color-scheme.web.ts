import { useEffect, useState } from 'react';
import { useColorScheme as useRNColorScheme } from 'react-native';

/**
 * To support static rendering, this value needs to be re-calculated on the client side for web
 */
export function useColorScheme() {
  const [hasHydrated, setHasHydrated] = useState(false);

  useEffect(() => {
    // Web static-rendering hydration guard: flip after mount so SSR markup and
    // first client render match. Deliberate one-time effect — rule is the new
    // react-hooks/set-state-in-effect; the useSyncExternalStore rewrite isn't
    // worth it for a web-only file (app targets Android first).
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setHasHydrated(true);
  }, []);

  const colorScheme = useRNColorScheme();

  if (hasHydrated) {
    return colorScheme;
  }

  return 'light';
}
